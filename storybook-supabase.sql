-- Storybook School schema (PostgreSQL / Supabase: paste into the SQL editor and run)
CREATE TABLE IF NOT EXISTS users(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK(role IN('admin','teacher','student')),
  username TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  pass_hash TEXT NOT NULL,             -- scrypt with a per-user salt
  level TEXT,                          -- pupil: P.1..P.6 | teacher: classes taught, for example P.4 and P.5
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN('pending','approved','rejected','disabled')),
  must_change INTEGER NOT NULL DEFAULT 0,
  fails INTEGER NOT NULL DEFAULT 0,
  locked_until BIGINT NOT NULL DEFAULT 0,
  created_by BIGINT,
  created_at BIGINT NOT NULL,
  approved_at BIGINT
);
CREATE TABLE IF NOT EXISTS sessions(
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL,
  ip TEXT
);
CREATE TABLE IF NOT EXISTS tests(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  level TEXT NOT NULL,
  story TEXT NOT NULL,
  questions TEXT NOT NULL,             -- JSON with answers; never sent to pupils
  total INTEGER NOT NULL,
  published INTEGER NOT NULL DEFAULT 0,
  author_id BIGINT NOT NULL REFERENCES users(id),
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS attempts(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  test_id BIGINT NOT NULL REFERENCES tests(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'started' CHECK(status IN('started','done')),
  answers TEXT,
  got INTEGER,
  by_level TEXT,                       -- JSON marks per Bloom level
  started_at BIGINT NOT NULL,
  finished_at BIGINT,
  UNIQUE(test_id,user_id)
);
CREATE TABLE IF NOT EXISTS audit(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at BIGINT NOT NULL,
  user_id BIGINT,
  action TEXT NOT NULL,
  detail TEXT,
  ip TEXT
);
CREATE INDEX IF NOT EXISTS ix_att_user ON attempts(user_id);
CREATE INDEX IF NOT EXISTS ix_att_test ON attempts(test_id);
CREATE INDEX IF NOT EXISTS ix_users_status ON users(status);

-- Lock the tables away from the Supabase public API; only the app server connection can use them.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE tests ENABLE ROW LEVEL SECURITY;
ALTER TABLE attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit ENABLE ROW LEVEL SECURITY;

